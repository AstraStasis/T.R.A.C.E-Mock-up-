"""Acceptance checks for the November concept UI. Requires local server and Edge."""
from pathlib import Path
import json
import os
from playwright.sync_api import sync_playwright, expect

BASE=os.getenv('TRACE_URL','http://127.0.0.1:8000')

out=Path('runtime/concept-screenshots');out.mkdir(exist_ok=True)
errors=[];external=[];checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:external.append(r.url) if not r.url.startswith((BASE,'data:')) else None)
    page.request.post(BASE+'/api/concept/command',data={'action':'disconnect'})
    for width,height in [(1280,800),(800,480),(390,844)]:
        page.set_viewport_size({'width':width,'height':height})
        for name in ['experiments','monitor','virtual','connection']:
            page.goto(BASE+'/#'+name)
            page.wait_for_selector('h1')
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth'),(width,name)
            if name=='virtual':expect(page.get_by_role('button',name='Activate on trainer',exact=True)).to_be_disabled()
            if name=='monitor':
                page.locator('#examples').check()
                expect(page.locator('#measurements')).to_contain_text('UNDEFINED')
                expect(page.locator('#measurement-source')).to_contain_text('OFFLINE EXAMPLES')
            page.screenshot(path=str(out/f'{width}-{name}.png'),full_page=True)
            checks.append([width,height,name])
    page.set_viewport_size({'width':1280,'height':800})
    page.goto(BASE+'/#experiments')
    expect(page.locator('h1')).to_contain_text('NOR and NAND gates')
    page.locator('button.link[data-exp="6"]').click()
    expect(page.locator('h1')).to_contain_text('Experiment 6')
    expect(page.locator('.switch-list')).to_contain_text('I7')
    page.locator('button.link[data-exp="9"]').click()
    expect(page.locator('h1')).to_contain_text('awaiting laboratory manual')
    page.goto(BASE+'/#connection')
    page.get_by_role('button',name='Start example session',exact=True).click()
    expect(page.locator('#session-summary')).to_contain_text('CONNECTED AND INACTIVE')
    page.locator('[data-page="virtual"]').click()
    expect(page.get_by_role('button',name='Configure example',exact=True)).to_be_disabled()
    expect(page.locator('#port-area')).to_contain_text('/1PRE')
    page.select_option('#model','74LS00')
    page.select_option('[data-signal="1B"]','15/A-E')
    expect(page.locator('#port-area .pcell.conflict')).to_have_count(1)
    expect(page.locator('#port-area')).to_contain_text('Node conflict')
    page.select_option('[data-signal="1B"]','16/A-E')
    expect(page.locator('#port-area .pcell.conflict')).to_have_count(0)
    page.get_by_role('button',name='Configure example',exact=True).click()
    expect(page.locator('#session-summary')).to_contain_text('CONFIGURED')
    expect(page.get_by_role('button',name='Activate example',exact=True)).to_be_disabled()
    page.locator('[data-confirm="wiring"]').check()
    expect(page.locator('[data-confirm="wiring"]')).to_be_checked()
    page.locator('[data-confirm="wiring"]').uncheck()
    expect(page.get_by_role('button',name='Activate example',exact=True)).to_be_disabled()
    page.locator('[data-confirm="wiring"]').check()
    page.select_option('[data-signal="1A"]','21/F-J')
    expect(page.locator('[data-confirm="wiring"]')).not_to_be_checked()
    page.select_option('[data-signal="1A"]','15/A-E')
    expect(page.get_by_role('button',name='Activate example',exact=True)).to_be_disabled()
    page.locator('[data-confirm="wiring"]').check()
    page.get_by_role('button',name='Activate example',exact=True).click()
    expect(page.locator('#session-summary')).to_contain_text('Simulated output enable: ENABLED')
    expect(page.get_by_role('button',name='Activate on trainer',exact=True)).to_be_disabled()
    expect(page.locator('#model')).to_be_disabled()
    page.locator('[data-input="1A"]').click()
    page.locator('[data-input="1B"]').click()
    expect(page.locator('[data-input="1B"]')).to_have_text('HIGH')
    expect(page.locator('#port-area .pcell.output.live.LOW')).to_have_count(1)
    response=page.request.post(BASE+'/api/concept/rehearsal-input',data={'signal':'1A','value':0})
    assert response.ok
    expect(page.locator('[data-input="1A"]')).to_have_text('LOW')
    expect(page.locator('#port-area .pcell.output.live.LOW')).to_have_count(0)
    expect(page.locator('.port-overview .node')).to_have_count(126)
    page.screenshot(path=str(out/'1280-virtual-active.png'),full_page=True)
    page.get_by_role('button',name='Deactivate example',exact=True).click()
    expect(page.locator('#session-summary')).to_contain_text('DISABLED')
    page.locator('[data-confirm="power"]').check()
    expect(page.locator('.procedure-panel')).to_contain_text('Session cycle complete')
    page.locator('[data-confirm="power"]').uncheck()
    expect(page.locator('[data-confirm="power"]')).not_to_be_checked()
    expect(page.locator('.procedure-panel')).not_to_contain_text('Session cycle complete')
    page.locator('[data-confirm="power"]').check()
    page.get_by_role('button',name='Offline behavior check',exact=True).click()
    page.get_by_role('button',name='J = 0',exact=True).click()
    page.get_by_role('button',name='Apply logical step',exact=True).click()
    expect(page.locator('.large-number').last).to_contain_text('Q 1')
    page.request.post(BASE+'/api/concept/command',data={'action':'disconnect'})
    assert not errors,errors
    assert not external,external
    browser.close()
Path('runtime/concept-browser-results.json').write_text(json.dumps({'viewports':checks,'errors':errors,'external_requests':external},indent=2))
print('12 page/viewport checks and offline lifecycle/logic checks passed; no JS errors or external requests.')
